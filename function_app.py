import azure.functions as func
import logging
import json
import hmac
import time
import uuid

from functools import wraps
from azure.identity import DefaultAzureCredential
from azure.keyvault.secrets import SecretClient
from microsoft.opentelemetry import use_microsoft_opentelemetry

# ------------------------------------------------------------
# Application Insights / OpenTelemetry
# ------------------------------------------------------------

use_microsoft_opentelemetry(
    enable_azure_monitor=True,
    logger_name="heroes-api"
)

telemetry_logger = logging.getLogger("heroes-api")
telemetry_logger.setLevel(logging.INFO)

# ------------------------------------------------------------
# Key Vault configuration
# ------------------------------------------------------------

credential = DefaultAzureCredential()

secret_client = SecretClient(
    vault_url="https://kv-midterm-ferna.vault.azure.net/",
    credential=credential
)

# ------------------------------------------------------------
# Azure Functions configuration
# ------------------------------------------------------------

app = func.FunctionApp(
    http_auth_level=func.AuthLevel.FUNCTION
)

import repository

FIELDS = [
    "name", "aliases", "status", "culture",
    "sources", "historical_period", "description"
]

# ------------------------------------------------------------
# Helpers
# ------------------------------------------------------------

def response(data, status=200):
    """Return a JSON response."""

    return func.HttpResponse(
        json.dumps(data),
        status_code=status,
        mimetype="application/json"
    )

class APIError(Exception):

    def __init__(self, message, status):
        self.message = message
        self.status = status

def get_api_key():
    """Retrieve the API key from Azure Key Vault."""

    secret = secret_client.get_secret("HEROES-API-KEY")
    return secret.value

def get_admin_api_key():
    """Retrieve the administrator API key from Key Vault."""

    secret = secret_client.get_secret("HEROES-ADMIN-API-KEY")
    return secret.value

# ------------------------------------------------------------
# Centralized request handler and logging
# ------------------------------------------------------------

def handle_function(
    needs_json=False,
    needs_id=False,
    needs_existing_hero=False,
    admin_only=False
):

    def decorator(handler):

        @wraps(handler)
        def wrapper(req: func.HttpRequest, *args, **kwargs):

            # Generate a unique correlation ID.
            request_id = str(uuid.uuid4())

            endpoint = handler.__name__
            method = req.method

            start_time = time.perf_counter()

            # Shared context for every log generated by this request.
            log_context = {
                "api_request_id": request_id,
                "api_endpoint": endpoint,
                "http_method": method
            }

            req.api_request_id = request_id

            telemetry_logger.info(
                "API request started.",
                extra=log_context
            )

            try:

                # --------------------------------------------
                # API key authentication
                # --------------------------------------------

                key = get_api_key()

                provided_key = (
                    req.headers.get("X-API-Key") or ""
                )

                if not key:
                    raise APIError(
                        "Server authentication is not configured.",
                        500
                    )

                if not hmac.compare_digest(provided_key, key):
                    raise APIError("Unauthorized.", 401)

                # --------------------------------------------
                # Administrator authorization
                # --------------------------------------------

                if admin_only:
                    admin_key = get_admin_api_key()
                    provided_admin_key = (
                        req.headers.get("X-Admin-API-Key") or "")

                    if not admin_key:
                        raise APIError(
                            "Administrator authorization is not configured.",
                            500
                        )

                    if not hmac.compare_digest(
                        provided_admin_key,
                        admin_key
                    ):
                        raise APIError(
                            "Administrator authorization required.",
                            403
                        )

                # --------------------------------------------
                # JSON body validation
                # --------------------------------------------

                if needs_json:

                    try:
                        body = req.get_json()

                    except (ValueError, TypeError):
                        raise APIError(
                            "Invalid JSON request body.",
                            400
                        )

                    if not isinstance(body, dict):
                        raise APIError(
                            "Request body must be a JSON object.",
                            400
                        )

                    missing = [
                        field for field in FIELDS
                        if field not in body
                        or body[field] is None
                        or body[field] == ""
                    ]

                    if missing:
                        raise APIError(
                            "Missing required fields: "
                            + ", ".join(missing),
                            400
                        )

                    req.validated_body = body

                # --------------------------------------------
                # Hero ID validation
                # --------------------------------------------

                raw_id = req.params.get("id")

                if needs_id and not raw_id:
                    raise APIError(
                        "Missing hero ID.",
                        400
                    )

                if raw_id is not None:

                    if not raw_id.strip():
                        raise APIError(
                            "Invalid hero ID.",
                            400
                        )

                    try:
                        hero_id = int(raw_id)

                    except (ValueError, TypeError):
                        raise APIError(
                            "Invalid hero ID.",
                            400
                        )

                    if hero_id <= 0:
                        raise APIError(
                            "Invalid hero ID.",
                            400
                        )

                    req.validated_hero_id = hero_id

                # --------------------------------------------
                # Hero existence validation
                # --------------------------------------------

                if needs_existing_hero and raw_id is not None:

                    hero = repository.get_hero(
                        req.validated_hero_id
                    )

                    if hero is None:
                        raise APIError(
                            "Hero not found.",
                            404
                        )

                    req.validated_hero = hero

                # --------------------------------------------
                # Execute endpoint
                # --------------------------------------------

                result = handler(req, *args, **kwargs)

                status_code = result.status_code

                duration = round(
                    (time.perf_counter() - start_time) * 1000,
                    2
                )

                completion_context = {
                    **log_context,
                    "http_status_code": status_code,
                    "duration_ms": duration
                }

                # --------------------------------------------
                # Log endpoint result
                # --------------------------------------------

                if status_code >= 500:

                    telemetry_logger.error(
                        "API request completed with server error.",
                        extra=completion_context
                    )

                elif status_code >= 400:

                    telemetry_logger.warning(
                        "API request completed with client error.",
                        extra=completion_context
                    )

                else:

                    telemetry_logger.info(
                        "API request completed successfully.",
                        extra=completion_context
                    )

                return result

            # --------------------------------------------
            # Expected API errors
            # --------------------------------------------

            except APIError as e:

                duration = round(
                    (time.perf_counter() - start_time) * 1000,
                    2
                )

                error_context = {
                    **log_context,
                    "http_status_code": e.status,
                    "duration_ms": duration,
                    "error_type": "APIError",
                    "error_message": e.message
                }

                if e.status >= 500:

                    telemetry_logger.error(
                        "API request failed.",
                        extra=error_context
                    )

                else:

                    telemetry_logger.warning(
                        "API request rejected.",
                        extra=error_context
                    )

                return response(
                    {"error": e.message},
                    e.status
                )

            # --------------------------------------------
            # Unexpected exceptions
            # --------------------------------------------

            except Exception as e:

                duration = round(
                    (time.perf_counter() - start_time) * 1000,
                    2
                )

                error_context = {
                    **log_context,
                    "http_status_code": 500,
                    "duration_ms": duration,
                    "error_type": type(e).__name__
                }

                telemetry_logger.exception(
                    "Unexpected API exception.",
                    extra=error_context
                )

                return response(
                    {"error": "Internal server error."},
                    500
                )

        return wrapper
    return decorator

# ------------------------------------------------------------
# POST - Create hero
# ------------------------------------------------------------

@app.route(route="heroes", methods=["POST"])
@handle_function(needs_json=True)
def create_hero(req: func.HttpRequest):

    hero = repository.create_hero(
        req.validated_body
    )

    return response(hero, 201)

# ------------------------------------------------------------
# GET - Retrieve heroes
# ------------------------------------------------------------

@app.route(route="heroes", methods=["GET"])
@handle_function(needs_existing_hero=True)
def get_hero(req: func.HttpRequest):

    if req.params.get("id") is None:
        return response(repository.get_all_heroes())

    return response(req.validated_hero)

# ------------------------------------------------------------
# PUT - Update hero
# ------------------------------------------------------------

@app.route(route="heroes", methods=["PUT"])
@handle_function(
    needs_json=True,
    needs_id=True,
    needs_existing_hero=True
)
def update_hero(req: func.HttpRequest):

    hero = repository.update_hero(
        req.validated_hero_id,
        req.validated_body
    )

    return response(hero)

# ------------------------------------------------------------
# DELETE - Delete individual hero
# ------------------------------------------------------------

@app.route(route="heroes", methods=["DELETE"])
@handle_function(
    needs_id=True,
    needs_existing_hero=True
)
def delete_hero(req: func.HttpRequest):

    hero_name = repository.delete_hero(
        req.validated_hero_id
    )

    return response({
        "message": f"Hero '{hero_name}' deleted successfully."
    })

# ------------------------------------------------------------
# PURGE - Delete all heroes
# ------------------------------------------------------------

@app.route(route="heroes/purge", methods=["DELETE"])
@handle_function(admin_only=True)
def purge_heroes(req: func.HttpRequest):

    total = repository.purge_heroes()

    telemetry_logger.info(
        "Heroes purge completed.",
        extra={
            "microsoft.custom_event.name": "HeroesPurged",
            "deleted_count": total,
            "operation": "AdministrativePurge",
            "authorization_method": "AdminAPIKey"
        }
    )

    return response({
        "message": "All heroes have been purged successfully.",
        "deleted": total
    })

# ------------------------------------------------------------
# COUNTS - Count all heroes
# ------------------------------------------------------------

@app.route(route="heroes/counts", methods=["GET"])
@handle_function()
def count_heroes(req: func.HttpRequest):

    return response({
        "count": repository.count_heroes()
    })

# ------------------------------------------------------------
# PATCH - Validate all heroes
# ------------------------------------------------------------

@app.route(route="heroes/validate", methods=["PATCH"])
@handle_function(admin_only=True)
def validate_heroes(req: func.HttpRequest):

    telemetry_logger.info(
        "Batch validation started.",
        extra={
            "microsoft.custom_event.name": "ValidationTriggered",
            "entity": "Heroes",
            "operation": "BatchValidation"
        }
    )

    result = repository.validate_heroes()

    telemetry_logger.info(
        "Batch validation completed.",
        extra={
            "microsoft.custom_event.name": "ValidationCompleted",
            "entity": "Heroes",
            "operation": "BatchValidation",
            "updated_count": result["updatedCount"]
        }
    )

    return response(result)